Detta är filen .../info/dir som innehåller den översta noden i
Info-hierarkin som kallas (kat)Top.
Första gången du använder Info börjar du med denna nod.

File: dir,	Node: Top	Detta är översta noden i INFO-trädet

  Denna nod (katalognoden) erbjuder en meny med huvudrubriker.
  Att skriva ”q” avslutar, ”H” visar alla Info-kommandon, ”d”
  återvänder hit, ”h” visar en hjälp för förstagångsanvändare,
  ”mEmacs<Retur>” besöker Emacs-manualen, osv.

  I Emacs kan du klicka med musknapp 2 på en menypost eller korsreferens
  för att välja den.

